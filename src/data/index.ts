export const listings: Listing[] = seeds.map((s) => {
  const { cover, ...rest } = s;
  const gallery = [cover, ...GALLERY.filter((g) => g !== cover)];
  return {
    ...rest,
    images: gallery.map((url, i) => ({
      id: `${s.id}-img-${i}`,
      url,
      alt: `${s.title} — view ${i + 1}`,
      isCover: i === 0,
    })),
  } satisfies Listing;
});

